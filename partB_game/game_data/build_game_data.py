"""Builds src/data.js: a compact real-data pool for the game, from data/ai4i2020.csv (UCI AI4I 2020).
Pool = ALL 339 real failures + 900 randomly chosen healthy cycles (seed 7).  The game re-samples
from this pool so that failures are over-represented enough to be playable (real rate is 3.4%)."""
import json, sys
from pathlib import Path
import numpy as np, pandas as pd
root = Path(__file__).resolve().parents[2]
df = pd.read_csv(root / "data" / "ai4i2020.csv", encoding="utf-8-sig")
df.columns = ["udi","pid","type","air","proc","rpm","torque","wear","y","twf","hdf","pwf","osf","rnf"]
def mode(r):
    for i, m in enumerate(["twf","hdf","pwf","osf","rnf"], 1):
        if r[m]: return i
    return 0
df["mode"] = df.apply(mode, axis=1)
fail = df[df.y == 1]
ok = df[df.y == 0].sample(900, random_state=7)
pool = pd.concat([fail, ok]).sample(frac=1, random_state=7)
rows = [[int(r.udi), "LMH".index(r.type), float(r.air), float(r.proc), int(r.rpm), float(r.torque), int(r.wear), int(r["mode"]), int(r.y)] for _, r in pool.iterrows()]
out = root / "partB_game" / "src" / "data.js"
out.write_text("// AUTO-GENERATED by game_data/build_game_data.py from the UCI AI4I 2020 dataset (CC BY 4.0)\n"
               "// row = [udi, typeIdx(L,M,H), airK, procK, rpm, torqueNm, wearMin, failureModeCode, failed]\n"
               "// mode codes: 0 none, 1 TWF tool wear, 2 HDF heat, 3 PWF power, 4 OSF overstrain, 5 RNF random\n"
               "const POOL=" + json.dumps(rows, separators=(",", ":")) + ";\n")
print(len(rows), "rows,", int(pool.y.sum()), "failures,", out.stat().st_size // 1024, "KB")
